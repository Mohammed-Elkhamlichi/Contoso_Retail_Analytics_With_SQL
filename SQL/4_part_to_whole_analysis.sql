/* 
Phase 4:  Part-to-Whole Analysis 
Measure the relative revenue and volume contribution of individual dimensions (such as product categories, subcategories, or sales regions) against the total portfolio baseline to identify core revenue drivers and structural portfolio reliance.
====================================================================
Which categories contribute the most to overall revenue?
====================================================================
*/
-- ==================================================================== --
WITH category_revenue AS (
    SELECT 
        p.categoryname,
        -- Total revenue generated by each product category
        ROUND(SUM(s.quantity * s.netprice * s.exchangerate)) AS total_revenue_by_category
    FROM
    sales s
    -- Join the product table to access category information
    LEFT JOIN product p ON p.productkey = s.productkey

    GROUP BY
        p.categoryname

)SELECT 
    categoryname,
    total_revenue_by_category,
    -- total revenue across all categories
    SUM(total_revenue_by_category) OVER () AS total_revenue_all_categories,
    -- Calculate the percentage contribution of each category to the total revenue
    ROUND(
        (
            total_revenue_by_category::NUMERIC / SUM(total_revenue_by_category) OVER ()::NUMERIC
        )*100, 2
    ) AS percentage_contribution_to_total_revenue
    
FROM category_revenue 

-- Order the results by percentage contribution to total revenue in descending order to identify the top-performing categories
ORDER BY percentage_contribution_to_total_revenue DESC;
