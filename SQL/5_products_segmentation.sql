/* 
Phase 5: Products Segmentation & Profiling
Objective: Segment products into cost ranges and count the number of products in each range to identify pricing strategies and product positioning.
====================================================================
*/
-- ==================================================================== --
WITH product_segmentation AS (
    SELECT 
        productkey,
        productname,
        cost,

        -- Categorize products into cost ranges based on their standard cost
        CASE WHEN cost < 10 THEN 'Low'
            WHEN cost BETWEEN 10 AND 100 THEN 'Medium'
            WHEN cost BETWEEN 100 AND 500 THEN 'High'
            WHEN cost BETWEEN 500 AND 1000 THEN 'Premium'
            ELSE 'Luxury'
        END AS cost_range
    FROM product

)SELECT 
    -- Count the number of products in each cost range to understand the distribution of products across different pricing tiers
    COUNT(ps.productkey) AS total_products,

    ps.cost_range,

    -- Calculate the total net revenue generated by products in each cost range to assess their financial contribution
    ROUND(SUM(s.quantity * s.netprice * s.exchangerate)) AS total_generated_revenue
    
FROM product_segmentation ps
LEFT JOIN sales s ON s.productkey = ps.productkey

GROUP BY 
    cost_range
ORDER BY total_generated_revenue DESC
